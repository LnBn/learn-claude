#!/usr/bin/env python3
"""
programme — one course made of units from several book courses, grouped into topic modules.

Each book course keeps its page map, figures, exercises, chapter notes and progress (book.py). A programme adds
only the order of the units and their grouping into modules. While a programme is current, `next` and `section`
make the unit's book the current course, so every book.py command, /exercise, /exam and the figures act on it.

    programme.py new <name> --title T [--goal G]
                                     create courses/<name>/ with its programme note <name>.md
    programme.py module "<title>" <course>:<spec> [<course>:<spec> | <spec> ...] [--at N]
                                     add a module (or replace the units of the module with that title); a spec is
                                     as in book.py select, and one without a prefix belongs to the course before it
    programme.py move <n> <to>       move module n to position <to>
    programme.py remove <n>          remove module n
    programme.py set <title|goal> <value>
    programme.py next                the next unit of the programme (book.py next when no programme is current)
    programme.py section [<course>:]<unit>
                                     a given unit (book.py section when no programme is current)
    programme.py done [<course>:]<unit> [--status done|shaky|skipped|todo]
                                     record the unit in its book; prints what comes next in the programme
    programme.py status              progress per module and overall (book.py status when no programme is current)
    programme.py list                programmes and courses, the current one marked
    programme.py use <name>          make a programme current, or a course (as book.py use)
    programme.py members             the directories of the current programme's books, one per line
    programme.py index               regenerate the programme note's index
    programme.py off                 no programme is current any more

A programme is current when md-log-state/programme.json names it and the current course is one of its books.
Changing the modules sets each book's syllabus to its units in the programme plus the units it has done.
"""
import argparse
import os
import re
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import book  # noqa: E402
import sections  # noqa: E402

PPOINTER = os.path.join(book.CLAUDE_DIR, "md-log-state", "programme.json")
INDEX_START = ("%% Generated by .claude/hooks/programme.py from .programme/programme.json, down to the end line. "
               "Edits there are overwritten. %%")
INDEX_END = "%% /programme index %%"
MODULE_RE = re.compile(r"^## +Module \d+ — (.+?)\s*$")


def same(a, b):
    return bool(a and b) and os.path.realpath(a) == os.path.realpath(b)


def is_programme(d):
    return os.path.exists(os.path.join(d, ".programme", "programme.json"))


def is_course(d):
    return os.path.exists(os.path.join(d, ".course", "book.json"))


def courses_root():
    return os.path.join(os.getcwd(), "courses")


class Programme:
    def __init__(self, pdir):
        self.dir = os.path.abspath(pdir)
        self.path = os.path.join(self.dir, ".programme", "programme.json")
        self.state = book.load_json(self.path, None)
        if not self.state:
            book.die(f"not a programme directory (no .programme/programme.json): {pdir}")
        self.state.setdefault("modules", [])
        self.slug = self.state["slug"]
        self._courses = {}

    # --- books
    def course_dir(self, name):
        return os.path.join(os.path.dirname(self.dir), name)

    def course(self, name):
        if name not in self._courses:
            d = self.course_dir(name)
            if not is_course(d):
                book.die(f"no course named {name} (expected {book.rel(d)}/.course/book.json); see: programme.py list")
            self._courses[name] = book.Course(d)
        return self._courses[name]

    def members(self):
        out = []
        for m in self.state["modules"]:
            for name, _ in m["units"]:
                if name not in out:
                    out.append(name)
        return out

    def name_of(self, cdir):
        return next((n for n in self.members() if same(self.course_dir(n), cdir)), None)

    # --- units
    def units(self):
        """[(module index, course name, unit id)] in programme order, without units the book no longer has."""
        return [(i, name, uid) for i, m in enumerate(self.state["modules"]) for name, uid in m["units"]
                if uid in self.course(name).by_id]

    def status(self, name, uid):
        return self.course(name).status(uid)

    def next_unit(self):
        return next((x for x in self.units() if self.status(x[1], x[2]) == "todo"), None)

    def module_units(self, i):
        return [(n, u) for j, n, u in self.units() if j == i]

    # --- the programme note
    def note(self):
        return os.path.join(self.dir, self.slug + ".md")

    def body(self):
        """Everything below the index: the module overviews written by the mirror."""
        try:
            with open(self.note(), encoding="utf-8") as f:
                text = f.read()
        except OSError:
            return ""
        head, sep, rest = text.partition(INDEX_END + "\n")
        if not sep:
            head, sep, rest = text.partition(INDEX_END)
        return rest if sep else text

    def heading(self, i):
        return f"## Module {i + 1} — {self.state['modules'][i]['title']}"

    def started(self, i):
        want = sections._anchor(self.state["modules"][i]["title"])
        return any(sections._anchor(m.group(1)) == want for m in map(MODULE_RE.match, self.body().split("\n")) if m)

    def module_link(self, i, label=None):
        anchor = sections._anchor(self.heading(i))
        return f"[[{self.slug}#{anchor}|{label or f'module {i + 1} overview'}]]"

    def save(self):
        book.save_json(self.path, self.state)
        self.write_index()

    def write_index(self):
        body = self.body()
        text = render_index(self) + ("\n" + body.lstrip("\n") if body.strip() else "")
        try:
            with open(self.note(), encoding="utf-8") as f:
                if f.read() == text:
                    return
        except OSError:
            pass
        with open(self.note(), "w", encoding="utf-8") as f:
            f.write(text)


def pointed():
    """The programme the pointer names, current or not."""
    d = book.load_json(PPOINTER, {}).get("programme")
    return Programme(d) if d and is_programme(d) else None


def current():
    """The current programme: the pointer names it and the current course is one of its books (or it has none)."""
    p = pointed()
    if p is None:
        return None
    members = p.members()
    last = book.load_json(book.POINTER, {}).get("course")
    if members and not any(same(p.course_dir(n), last) for n in members):
        return None
    return p


def programme_for(a):
    if getattr(a, "programme", None):
        d = os.path.join(courses_root(), a.programme)
        if not is_programme(d):
            book.die(f"no programme named {a.programme}; see: programme.py list")
        return Programme(d)
    p = pointed()
    if p is None:
        book.die("no programme yet — create one with: programme.py new <name> --title \"<title>\"")
    return p


def set_course(c):
    book.save_json(book.POINTER, {"course": c.dir})


def follow(p):
    """Make the book of the programme's next unit (else its first book) the current course."""
    nxt = p.next_unit()
    name = nxt[1] if nxt else (p.members() or [None])[0]
    if name:
        set_course(p.course(name))


def chapter_of(u):
    return u["chapter"] or u["id"]


# ---------------------------------------------------------------- the index

def unit_link(c, u, cache):
    """`[[bh-ch07#7.1 Joint distributions|§7.1 Joint distributions]]` once the chapter note has a heading for it."""
    label = f"§{u['id']} {u['title']}"
    note = c.note(chapter_of(u))
    if note not in cache:
        try:
            with open(note, encoding="utf-8") as f:
                cache[note] = sections.headings(f.read())
        except OSError:
            cache[note] = []
    target = sections.resolve(u["id"], cache[note]) if cache[note] else None
    if not target:
        return label
    return f"[[{os.path.splitext(os.path.basename(note))[0]}#{target}|{label}]]"


def render_index(p):
    st = p.state
    units = p.units()
    n_done = sum(1 for _, n, u in units if p.status(n, u) in ("done", "shaky"))
    out = [f"# {st.get('title') or p.slug}", "", INDEX_START, ""]
    if p.members():
        out.append("Books: " + " · ".join(f"[[{p.course(n).slug}]]" for n in p.members()))
        out.append("")
    nxt = p.next_unit()
    out.append(f"{n_done} of {len(units)} units studied"
               + (f" · next: module {nxt[0] + 1}, {nxt[1]} §{nxt[2]}" if nxt else ""))
    if st.get("goal"):
        out += ["", f"Goal: {st['goal']}"]
    out += ["", "## Modules"]
    if not st["modules"]:
        out += ["", "No modules yet."]
    cache = {}
    for i, m in enumerate(st["modules"]):
        mu = p.module_units(i)
        d = sum(1 for n, u in mu if p.status(n, u) in ("done", "shaky"))
        ov = f" · [[#{sections._anchor(p.heading(i))}|overview]]" if p.started(i) else ""
        out += ["", f"{i + 1}. **{m['title']}** — {d} of {len(mu)} studied{ov}", ""]
        for name, uid in mu:
            c = p.course(name)
            u = c.by_id[uid]
            s = c.status(uid)
            box = {"todo": "[ ]", "done": "[x]", "shaky": "[x]", "skipped": "[-]"}[s]
            tail = " — shaky, revisit" if s == "shaky" else " — skipped" if s == "skipped" else ""
            out.append(f"    - {box} {name} {unit_link(c, u, cache)} · {c.cite(u['start'], u['end'])}{tail}")
    out += ["", INDEX_END]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- output

def progress(p, units=None):
    units = p.units() if units is None else units
    n = {s: sum(1 for _, nm, u in units if p.status(nm, u) == s) for s in book.UNIT_STATUS}
    return (f"{len(units)} units: {n['done']} done, {n['shaky']} shaky, {n['skipped']} skipped, "
            f"{n['todo']} to do")


def module_line(p, i):
    m = p.state["modules"][i]
    mu = p.module_units(i)
    d = sum(1 for n, u in mu if p.status(n, u) != "todo")
    mark = "✓" if mu and d == len(mu) else "·" if d == 0 else "…"
    return f"{mark} {i + 1} {m['title']} — {d} of {len(mu)} ({' '.join(m.get('spec') or [])})"


def describe(p, i, name, uid, heading="NEXT"):
    """The unit as book.py describes it, with the programme's lines around it."""
    c = p.course(name)
    u = c.by_id[uid]
    mods = p.state["modules"]
    mu = p.module_units(i)
    k = mu.index((name, uid)) + 1 if (name, uid) in mu else 0
    lines = [f"PROGRAMME: {p.state.get('title') or p.slug} — module {i + 1} of {len(mods)} \"{mods[i]['title']}\""
             + (f", unit {k} of {len(mu)}" if k else "") + f" · {name} §{uid}",
             f"COURSE: {name} — {c.state.get('title') or c.slug}  (now the current course: book.py commands act on it)"]
    if p.state.get("goal"):
        lines.append(f"PROGRAMME GOAL: {p.state['goal']}")
    if not p.started(i):
        lines.append(f"MODULE START: module {i + 1} has no overview yet. Link the programme note (md_log.py link "
                     f"--from-now --no-header) and write the module overview there under the heading below, before "
                     f"the unit. When the learner says ready, link the chapter note on the NOTE line and teach the unit.")
        lines.append(f"PROGRAMME NOTE: {book.rel(p.note())}")
        lines.append(f"HEADING: {p.heading(i)}")
        lines.append("MODULE UNITS (in order):")
        cache = {}
        for n, x in mu:
            cx = p.course(n)
            ux = cx.by_id[x]
            note = cx.note(chapter_of(ux))
            ch = cx.by_id.get(ux["chapter"]) if ux.get("chapter") else None
            lines.append(f"  {'→' if (n, x) == (name, uid) else book.MARK[cx.status(x)]} {n} "
                         f"{unit_link(cx, ux, cache)} · PDF pages {cx.pages(ux['start'], ux['end'])[0]} "
                         f"({cx.cite(ux['start'], ux['end'])})"
                         + (f" · chapter {ch['id']} \"{ch['title']}\"" if ch else "")
                         + f" · note {os.path.splitext(os.path.basename(note))[0]}"
                         + ("" if os.path.exists(note) and os.path.getsize(note) else " (new)"))
        books = []
        for n, _ in mu:
            entry = f"{n} = {p.course(n).state.get('title') or n} ({p.course(n).book['pdf']})"
            if entry not in books:
                books.append(entry)
        lines.append("BOOKS: " + "; ".join(books))
    text = book.describe_unit(c, u, heading)
    if p.state.get("goal"):
        text = "\n".join(ln for ln in text.split("\n") if not ln.startswith("COURSE GOAL:"))
    lines.append(text)
    note = c.note(chapter_of(u))
    if not (os.path.exists(note) and os.path.getsize(note)):
        lines.append(f"PROGRAMME CHAPTER START: the chapter note is new and the chapter is reached through the "
                     f"programme. Open it with a short ### Overview of two or three sentences that links to "
                     f"{p.module_link(i)}, then teach the unit. No chapter-sized overview and no ready-or-probe choice.")
    lines.append(f"RECORD: when every node of the unit has passed, run programme.py done {name}:{uid} "
                 f"[--status shaky]; the next unit comes from its output, not from book.py.")
    return "\n".join(lines)


# ---------------------------------------------------------------- setup commands

def cmd_new(a):
    slug = book.slugify(a.name)
    pdir = os.path.join(courses_root(), slug)
    if is_programme(pdir) or is_course(pdir):
        book.die(f"{book.rel(pdir)} already holds a {'programme' if is_programme(pdir) else 'course'}")
    book.save_json(os.path.join(pdir, ".programme", "programme.json"),
                   {"slug": slug, "title": a.title or slug, "goal": a.goal or "", "modules": [],
                    "created": time.strftime("%Y-%m-%d")})
    book.save_json(PPOINTER, {"programme": pdir})
    p = Programme(pdir)
    p.save()
    print(f"🗒 programme created: {book.rel(pdir)}  (note: {book.rel(p.note())})")
    print("ADD MODULES: programme.py module \"<title>\" <course>:<spec> [<course>:<spec> ...]")


def parse_specs(p, tokens):
    """[(course name, spec)] from `bh:7.1-7.5 7.7 strang:3.3`; a token without a prefix continues the course."""
    out, name = [], None
    for tok in tokens:
        head, sep, rest = tok.partition(":")
        if sep and is_course(p.course_dir(head)):
            name, spec = head, rest
        elif name:
            spec = tok
        else:
            book.die(f"name the course of {tok}: <course>:<spec>, e.g. bh:7.1-7.5")
        if not spec:
            book.die(f"no sections after {name}:")
        out.append((name, spec))
    return out


def cmd_module(a):
    p = programme_for(a)
    mods = p.state["modules"]
    old = next((i for i, m in enumerate(mods) if m["title"] == a.title), None)
    units, specs = [], []
    for name, spec in parse_specs(p, a.specs):
        specs.append(f"{name}:{spec}")
        for uid in book.expand_spec(p.course(name), [spec]):
            if [name, uid] not in units:
                units.append([name, uid])
    if not units:
        book.die("no units in that selection")
    for i, m in enumerate(mods):
        if i == old:
            continue
        clash = [f"{n}:{u}" for n, u in units if [n, u] in m["units"]]
        if clash:
            book.die(f"already in module {i + 1} \"{m['title']}\": {', '.join(clash)} — a unit sits in one module only")
    before = p.members()
    mod = {"title": a.title, "spec": specs, "units": units}
    if old is not None:
        mods[old] = mod
        at = old
    else:
        at = len(mods) if a.at is None else max(0, min(len(mods), a.at - 1))
        mods.insert(at, mod)
    changed(p, before)
    per = {}
    for n, _ in units:
        per[n] = per.get(n, 0) + 1
    print(f"🗒 module {at + 1} \"{a.title}\" {'replaced' if old is not None else 'added'}: {len(units)} units ("
          + ", ".join(f"{n} {k}" for n, k in per.items()) + f") — programme {p.slug}: {len(mods)} modules, "
          f"{len(p.units())} units")
    print("UNITS: " + " · ".join(f"{n} {u}" for n, u in units))


def changed(p, before):
    """After the modules changed: each book's syllabus matches the programme; save; follow the next unit."""
    want = {}
    for name, uid in (x for m in p.state["modules"] for x in m["units"]):
        want.setdefault(name, set()).add(uid)
    for name in p.members():
        c = p.course(name)
        kept = {u for u, r in (c.state.get("status") or {}).items() if (r or {}).get("s") in ("done", "shaky")}
        keep = want[name] | kept
        syl = [u["id"] for u in c.units(appendices=True) if u["id"] in keep]
        if syl != (c.state.get("syllabus") or []):
            c.state["syllabus"] = syl
            c.save()
    p.save()
    follow(p)
    for name in before:
        if name not in p.members():
            print(f"note: {name} is no longer in the programme; its syllabus is left as it was", file=sys.stderr)


def module_index(p, n):
    if not 1 <= n <= len(p.state["modules"]):
        book.die(f"no module {n}; the programme has {len(p.state['modules'])}")
    return n - 1


def cmd_move(a):
    p = programme_for(a)
    i = module_index(p, a.n)
    mods = p.state["modules"]
    m = mods.pop(i)
    to = max(0, min(len(mods), a.to - 1))
    mods.insert(to, m)
    changed(p, p.members())
    print(f"🗒 module \"{m['title']}\" is now module {to + 1}")
    for j in range(len(mods)):
        print("  " + module_line(p, j))


def cmd_remove(a):
    p = programme_for(a)
    i = module_index(p, a.n)
    before = p.members()
    m = p.state["modules"].pop(i)
    changed(p, before)
    print(f"🗒 module \"{m['title']}\" removed — programme {p.slug}: {len(p.state['modules'])} modules, "
          f"{len(p.units())} units")


def cmd_set(a):
    p = programme_for(a)
    p.state[a.key] = " ".join(a.value).strip()
    p.save()
    print(f"🗒 programme {a.key} set: {p.state[a.key]}")


def cmd_index(a):
    p = programme_for(a)
    p.write_index()
    print(f"🗒 programme note: {book.rel(p.note())}")


def cmd_off(a):
    if os.path.exists(PPOINTER):
        os.remove(PPOINTER)
    print("🗒 no programme is current; book.py commands act on the current course alone")


def member_dirs():
    """The directories of the current programme's books, in programme order; [] when no programme is current.
    The default scope of an interview round while a programme runs."""
    p = current()
    return [p.course_dir(n) for n in p.members()] if p else []


def cmd_members(a):
    for d in member_dirs():
        print(d)


# ---------------------------------------------------------------- study commands

def split_target(p, target):
    """(course name, unit id) from `bh:7.1` or `7.1` (the current course)."""
    head, sep, rest = target.partition(":")
    if sep and is_course(p.course_dir(head)):
        return head, rest
    name = p.name_of(book.load_json(book.POINTER, {}).get("course"))
    if not name:
        book.die(f"name the book: <course>:{target}")
    return name, target


def where(p, name, uid):
    """The module index of a unit, or None when the programme does not hold it."""
    return next((i for i, n, u in p.units() if (n, u) == (name, uid)), None)


def alone(a):
    """No programme in play: `bh:7.1` still names the book; the rest is book.py's."""
    head, sep, rest = a.id.partition(":")
    if sep and not a.course and is_course(os.path.join(courses_root(), head)):
        a.course, a.id = os.path.join(courses_root(), head), rest
    return a


def cmd_next(a):
    p = current() if not a.course else None
    if p is None:
        return book.cmd_next(a)
    if not p.state["modules"]:
        book.die("the programme has no modules yet — programme.py module \"<title>\" <course>:<spec> ...")
    nxt = p.next_unit()
    p.write_index()
    if not nxt:
        shaky = [f"{n}:{u}" for _, n, u in p.units() if p.status(n, u) == "shaky"]
        print("PROGRAMME COMPLETE: every unit of every module is done."
              + (f" Shaky, worth revisiting: {', '.join(shaky)}" if shaky else ""))
        return
    set_course(p.course(nxt[1]))
    print(describe(p, *nxt))
    shaky = [f"{n}:{u}" for _, n, u in p.units() if p.status(n, u) == "shaky"]
    if shaky:
        print(f"SHAKY UNITS: {', '.join(shaky)}")


def cmd_section(a):
    p = current() if not a.course else None
    if p is None:
        return book.cmd_section(alone(a))
    name, uid = split_target(p, a.id)
    c = p.course(name)
    u = book.unit_for(c, uid)
    set_course(c)
    i = where(p, name, u["id"])
    if i is None:
        print(f"PROGRAMME: {p.state.get('title') or p.slug} — {name} §{u['id']} is not in the programme; "
              f"taught as a unit of {name} alone")
        print(f"COURSE: {name} — {c.state.get('title') or c.slug}  (now the current course: book.py commands act on it)")
        print(book.describe_unit(c, u))
        return
    print(describe(p, i, name, u["id"], "UNIT"))


def cmd_done(a):
    p = current() if not a.course else None
    if p is None:
        return book.cmd_done(alone(a))
    name, uid = split_target(p, a.id)
    c = p.course(name)
    u = book.unit_for(c, uid)
    set_course(c)
    if a.status == "todo":
        c.state["status"].pop(u["id"], None)
    else:
        c.state["status"][u["id"]] = {"s": a.status, "at": time.strftime("%Y-%m-%d")}
    if u["id"] not in (c.state.get("syllabus") or []):
        chosen = set(c.state.get("syllabus") or []) | {u["id"]}
        c.state["syllabus"] = [x["id"] for x in c.units(appendices=True) if x["id"] in chosen]
    c.save()
    p.write_index()
    print(f"🗒 {name} {u['id']} {u['title']}: {a.status} — programme: " + progress(p))
    here = where(p, name, u["id"])
    nxt = p.next_unit()
    ch = chapter_of(u)
    if not any(chapter_of(x) == ch and c.status(x["id"]) == "todo" for x in c.syllabus()):
        print(f"CHAPTER {ch} OF {name} COMPLETE (every unit of it in the syllabus is done).")
        print(f"EXAM: /exam {ch} sets an exam on this chapter of {name}.")
    if not nxt:
        print("PROGRAMME COMPLETE: no unit left to do.")
        return
    i, n2, u2 = nxt
    c2 = p.course(n2)
    x2 = c2.by_id[u2]
    if here is None or i != here:
        if not p.started(i):
            closed = f"MODULE {here + 1} \"{p.state['modules'][here]['title']}\" COMPLETE. " if here is not None else ""
            close = "close the module in two or three sentences and " if here is not None else ""
            print(f"{closed}The next unit, {n2} §{u2} {x2['title']}, opens module {i + 1} "
                  f"\"{p.state['modules'][i]['title']}\": {close}save a checkpoint; `/course next` opens module "
                  f"{i + 1} with its overview.")
            return
        if here is not None:
            print(f"MODULE {here + 1} \"{p.state['modules'][here]['title']}\" COMPLETE.")
    if (n2, chapter_of(x2)) != (name, ch):
        note = c2.note(chapter_of(x2))
        print(f"NEXT IN ANOTHER NOTE: {n2} §{u2} {x2['title']} ({os.path.splitext(os.path.basename(note))[0]}): save a "
              f"checkpoint; `/course next` starts it.")
    else:
        print(describe(p, i, n2, u2))


def cmd_status(a):
    p = current() if not a.course else None
    if p is None:
        return book.cmd_status(a)
    p.write_index()
    print(f"PROGRAMME: {p.state.get('title') or p.slug}  ({book.rel(p.dir)}; note {book.rel(p.note())})")
    if p.state.get("goal"):
        print(f"GOAL: {p.state['goal']}")
    print("PROGRESS: " + progress(p))
    print("MODULES: (✓ done · … started · · not started)")
    for i in range(len(p.state["modules"])):
        print("  " + module_line(p, i))
    shaky = [f"{n}:{u}" for _, n, u in p.units() if p.status(n, u) == "shaky"]
    if shaky:
        print(f"SHAKY: {', '.join(shaky)}")
    nxt = p.next_unit()
    if nxt:
        c = p.course(nxt[1])
        u = c.by_id[nxt[2]]
        print(f"NEXT: module {nxt[0] + 1} \"{p.state['modules'][nxt[0]]['title']}\" — {nxt[1]} §{u['id']} "
              f"{u['title']}  ({c.cite(u['start'], u['end'])})")
    print("BOOKS:")
    for n in p.members():
        print(f"  {n}: {book.progress_line(p.course(n))}")


def cmd_list(a):
    courses, last = book.course_dirs()
    root = courses_root()
    progs = [Programme(os.path.join(root, d)) for d in sorted(os.listdir(root))
             if is_programme(os.path.join(root, d))] if os.path.isdir(root) else []
    if not progs:
        return book.cmd_list(a)
    cur = current()
    shown = set()
    for p in progs:
        nxt = p.next_unit()
        on = cur is not None and same(cur.dir, p.dir)
        print(f"{'→' if on else ' '} {p.slug}: {p.state.get('title') or p.slug}  (programme, "
              f"{len(p.state['modules'])} modules)")
        print(f"    {progress(p)}" + (f"; next {nxt[1]} §{nxt[2]}" if nxt else ""))
        for n in p.members():
            c = p.course(n)
            shown.add(os.path.realpath(c.dir))
            print(f"    {'▸' if on and same(c.dir, last) else '·'} {n}: {c.state.get('title') or c.slug} — "
                  f"{book.progress_line(c)}")
    for d in courses:
        if os.path.realpath(d) in shown:
            continue
        c = book.Course(d)
        nxt = c.next_unit()
        print(f"{'→' if cur is None and same(d, last) else ' '} {os.path.basename(d)}: {c.state.get('title') or c.slug}")
        print(f"    {book.progress_line(c)}" + (f"; next {nxt['id']} {nxt['title']}" if nxt else ""))
    print("→ marks the current programme or course (▸ the book in use); switch with: /course use <name>")


def cmd_use(a):
    d = os.path.join(courses_root(), a.name)
    if is_programme(d):
        book.save_json(PPOINTER, {"programme": d})
        p = Programme(d)
        follow(p)
        p.write_index()
        nxt = p.next_unit()
        print(f"🗒 current programme: {p.slug} — {p.state.get('title') or p.slug}")
        print(progress(p) + (f"; next module {nxt[0] + 1}, {nxt[1]} §{nxt[2]}" if nxt else ""))
        return
    book.cmd_use(a)
    p = current()
    if p is not None:
        print(f"PROGRAMME: {p.slug} stays current ({a.name} is one of its books); `/course next` follows the programme")


